"""Profiles: a named set of agent configurations, and the one-time migration.

A profile is the answer to "which settings was this run using". Provider
switching already covers the endpoint; a profile covers everything else — model
tier defaults, effort levels, per-project trust, sandbox mode — and it is a
directory you can copy, diff or roll back.

Layout:

    <home>/profiles/<name>/profile.json     metadata (route, model, effort)
    <home>/profiles/<name>/<agent>.json     hand-editable overlay
    <home>/profiles/<name>/<agent>/<provider>/   the CLI's config home

The config home is *generated* from the overlay plus the provider, never hand
edited: that is what makes "the provider is the single source of truth" true
for Claude Code (which reads a JSON `env` block) and Codex (which reads a TOML
`experimental_bearer_token`) without two code paths that can drift.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import time
from dataclasses import dataclass
from pathlib import Path

from . import agents, config, providers

GENERATED = "generated by nodus from the profile overlay + provider"


@dataclass(frozen=True)
class Profile:
    name: str
    route: str | None = None
    model: str | None = None
    effort: str | None = None
    created_at: float = 0.0


# ---- paths -------------------------------------------------------------


def root() -> Path:
    return config.HOME / "profiles"


def dir_of(name: str | None = None) -> Path:
    return root() / (name or config.active_profile())


def home(
    agent: str, provider: str, profile: str | None = None
) -> Path:
    """The CLI config directory for one (profile, agent, provider).

    Keying on the provider is what keeps two concurrent runs on two endpoints
    from writing each other's settings: same inputs produce the same bytes, but
    different endpoints produce them in different places.
    """
    path = dir_of(profile) / agent / provider
    path.mkdir(parents=True, exist_ok=True)
    return path


def overlay_path(agent: str, profile: str | None = None) -> Path:
    return dir_of(profile) / f"{agent}.json"


def meta_path(profile: str | None = None) -> Path:
    return dir_of(profile) / "profile.json"


# ---- metadata ----------------------------------------------------------


def read(name: str | None = None) -> Profile:
    key = name or config.active_profile()
    try:
        data = json.loads(meta_path(key).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return Profile(name=key)
    return Profile(
        name=key,
        route=data.get("route") or None,
        model=data.get("model") or None,
        effort=data.get("effort") or None,
        created_at=float(data.get("created_at") or 0),
    )


def write(profile: Profile) -> None:
    dir_of(profile.name).mkdir(parents=True, exist_ok=True)
    meta_path(profile.name).write_text(
        json.dumps(
            {
                "name": profile.name,
                "route": profile.route,
                "model": profile.model,
                "effort": profile.effort,
                "created_at": profile.created_at or time.time(),
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
        encoding="utf-8",
    )


def names() -> list[str]:
    if not root().is_dir():
        return []
    return sorted(p.name for p in root().iterdir() if p.is_dir())


def ensure(name: str) -> Profile:
    profile = read(name)
    if not meta_path(name).exists():
        write(Profile(name=name, created_at=time.time()))
        profile = read(name)
    return profile


def use(name: str) -> None:
    if meta_path(name).exists() is False and name != "default":
        raise ValueError(f"unknown profile: {name} (nodus profile new {name})")
    data = config.load_config()
    data["profile"] = name
    config.ensure_dirs()
    config.config_path().write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def create(name: str, from_: str | None = None) -> Profile:
    target = dir_of(name)
    if target.exists():
        raise ValueError(f"profile already exists: {name}")
    target.mkdir(parents=True)
    if from_:
        source = dir_of(from_)
        if not source.is_dir():
            raise ValueError(f"unknown source profile: {from_}")
        for item in source.iterdir():
            if item.is_dir():
                shutil.copytree(item, target / item.name)
            else:
                shutil.copy2(item, target / item.name)
        data = json.loads(meta_path(name).read_text(encoding="utf-8"))
        data["name"] = name
        data["created_at"] = time.time()
        meta_path(name).write_text(
            json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    else:
        write(Profile(name=name, created_at=time.time()))
    return read(name)


def remove(name: str) -> None:
    if name == config.active_profile():
        raise ValueError("cannot remove the active profile; switch first")
    target = dir_of(name)
    if not target.is_dir():
        raise ValueError(f"unknown profile: {name}")
    shutil.rmtree(target)


# ---- overlay + materialisation ----------------------------------------


def overlay(agent: str, profile: str | None = None) -> dict:
    try:
        data = json.loads(overlay_path(agent, profile).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def write_overlay(agent: str, data: dict, profile: str | None = None) -> None:
    path = overlay_path(agent, profile)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def materialize(
    spec: agents.AgentSpec,
    provider: providers.Provider,
    secrets: dict[str, str],
    profile: str | None = None,
) -> Path:
    """Write this combination's config directory and return it."""
    path = home(spec.name, provider.name, profile)
    extra = overlay(spec.name, profile)
    if spec.vendor == "claude":
        settings = {k: v for k, v in extra.items() if k != "env"}
        settings.update(providers.cli_settings(provider))
        settings.pop("env", None)
        (path / "settings.json").write_text(
            json.dumps(settings, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    elif spec.vendor == "codex":
        (path / "config.toml").write_text(
            _toml_dump(_codex_config(provider, secrets, extra)) + "\n", encoding="utf-8"
        )
    return path


def _codex_config(
    provider: providers.Provider, secrets: dict[str, str], extra: dict
) -> dict:
    name = f"nodus-{provider.name}"
    block = {
        "name": provider.name,
        "wire_api": provider.wire_api,
        "requires_openai_auth": False,
    }
    if provider.base_url:
        block["base_url"] = provider.base_url
    token = providers.secret_value(provider, secrets)
    if token:
        # Inline rather than env_key: Codex resolves env_key from the config
        # file's own table and silently falls back to an unauthenticated call
        # when it is missing. The home is user-private, same as the old layout.
        block["experimental_bearer_token"] = token
    data = dict(extra)
    data.pop("model_providers", None)  # replaced, not merged: one route, one box
    data["model_provider"] = name
    if provider.model:
        data["model"] = provider.model
    data["model_providers"] = {**extra.get("model_providers", {}), name: block}
    return data


_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")


def _toml_key(key: str) -> str:
    key = str(key)
    return key if _BARE_KEY.match(key) else _toml_string(key)


def _toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(v) for v in value) + "]"
    return _toml_string(str(value))


def _toml_dump(data: dict, prefix: str = "") -> str:
    """Minimal TOML writer: scalars first, then one section per nested dict.

    A table is only given a header when it holds a scalar of its own; a table
    made purely of sub-tables is implied by its children and printing it empty
    would be noise in a file a human is meant to read.
    """
    lines: list[str] = []
    for key, value in data.items():
        if not isinstance(value, dict):
            lines.append(f"{_toml_key(key)} = {_toml_value(value)}")
    for key, value in data.items():
        if not isinstance(value, dict):
            continue
        name = f"{prefix}.{_toml_key(key)}" if prefix else _toml_key(key)
        if any(not isinstance(v, dict) for v in value.values()):
            lines.append("")
            lines.append(f"[{name}]")
        body = _toml_dump(value, name)
        if body:
            lines.append(body)
    return "\n".join(lines)


# ---- one-time bootstrap ------------------------------------------------


#: What the pre-provider layout implied: agent -> (agent, provider).
LEGACY = {
    "claude": ("claude", "relay"),
    "minimax": ("claude", "minimax"),
    "codex": ("codex", "relay-openai"),
}


def ensure_ready() -> None:
    """Run the one-time upgrade exactly once, safely, against concurrent starts.

    Called by the daemon and by the CLI. Both can start at the same moment; the
    lock file makes the second caller a no-op rather than a second migration.
    """
    legacy = config.HOME / "agents"
    if providers.path().exists() and not legacy.exists():
        return
    config.ensure_dirs()
    lock = config.HOME / "bootstrap.lock"
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        return
    try:
        if not providers.path().exists():
            providers.bootstrap()
        _migrate(legacy)
        ensure("default")
    finally:
        os.close(fd)
        try:
            lock.unlink()
        except OSError:
            pass


def _migrate(legacy: Path) -> None:
    if not legacy.is_dir():
        return
    stamp = time.strftime("%Y%m%d-%H%M%S")
    backup = config.HOME / "backup" / f"agents-{stamp}"
    moved = 0
    for old, (agent, provider) in LEGACY.items():
        source = legacy / old
        if not source.is_dir():
            continue
        target = home(agent, provider, "default")
        if any(target.iterdir()):
            continue  # already migrated by an earlier run; never overwrite
        backup.mkdir(parents=True, exist_ok=True)
        for name in ("settings.json", "config.toml"):
            if (source / name).exists():
                shutil.copy2(source / name, backup / f"{old}-{name}")
        try:
            target.rmdir()  # drop the placeholder `home()` just created
            shutil.move(str(source), str(target))
        except OSError:
            continue
        _seed_overlay(agent, target)
        moved += 1
    if moved:
        try:
            legacy.rmdir()  # only when nothing unknown was left behind
        except OSError:
            pass


def _seed_overlay(agent: str, source: Path) -> None:
    """Keep the provider-independent part of the old config as a hand-editable overlay."""
    if overlay_path(agent).exists():
        return
    if (source / "settings.json").exists():
        try:
            data = json.loads((source / "settings.json").read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return
        keep = {
            k: v
            for k, v in data.items()
            if k not in ("env", "model") and not k.startswith("ANTHROPIC_")
        }
        if keep:
            write_overlay(agent, keep)
    elif (source / "config.toml").exists():
        try:
            import tomllib

            data = tomllib.loads((source / "config.toml").read_text(encoding="utf-8"))
        except (OSError, ImportError, ValueError):
            return
        keep = {
            k: v
            for k, v in data.items()
            if k not in ("model", "model_provider", "model_providers")
        }
        if keep:
            write_overlay(agent, keep)
